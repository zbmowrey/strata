// GardenEnv marks a session started by the gardener (`strata garden`); such
// sessions may not write the private tier (docs/spec/07-gardener.md §6).
const GardenEnv = "STRATA_GARDEN"

// generatedMarker identifies fully generated files by their first line.
const generatedMarker = "GENERATED by strata"

// managedBlocks are the marker pairs Strata owns inside otherwise
// hand-written files, with the command that regenerates each.
var managedBlocks = []struct {
	m   fsutil.Markers
	cmd string
}{
	{scaffold.ClaudeMarkers, "strata upgrade"},
	{scaffold.LocalMarkers, "strata init"},
	{projects.GitignoreMarkers, "strata project sync"},
	{knowledge.HubMarkers, "strata garden"},
}

// preEdit guards generated content and, once per path, surfaces the
// documents whose applies_to globs match the file.
func (h *handler) preEdit() (outcome, error) {
	abs := h.in.EditPath()
	rel, ok := h.rel(abs)
	if !ok {
		return outcome{label: "outside"}, nil
	}
	if msg := h.guard(abs, rel); msg != "" {
		return outcome{stderr: msg + "\n", code: 2, label: "blocked"}, nil
	}
	if !h.inst.Config.Hooks.PreEditContext {
		return outcome{label: "ok"}, nil
	}
	first := false
	if err := update(h.inst.Root, h.in.SessionID, func(s *State) { first = s.markEdited(rel) }); err != nil {
		return outcome{}, err
	}
	if !first {
		return outcome{label: "ok"}, nil
	}
	text, err := h.advisory(rel)
	if err != nil || text == "" {
		return outcome{label: "ok"}, err
	}
	return outcome{stdout: additionalContext("PreToolUse", text), label: "advised"}, nil
}

// guard returns a block message, or "" when the edit may proceed.
func (h *handler) guard(abs, rel string) string {
	private := h.inst.Config.Paths.Knowledge + "/_private/"
	if os.Getenv(GardenEnv) == "1" && strings.HasPrefix(rel+"/", private) {
		return "strata: gardener sessions may not write " + private + " (docs/spec/07-gardener.md §6)"
	}
	cur, err := os.ReadFile(abs) //nolint:gosec // G304: the path Claude is about to edit, inside the instance
	if err != nil {
		return "" // new file
	}
	if first, _, _ := bytes.Cut(cur, []byte("\n")); bytes.Contains(first, []byte(generatedMarker)) {
		return fmt.Sprintf("strata: %s is generated — %s", rel, strings.TrimSpace(stripComment(string(first))))
	}
	e := h.in.Edit()
	for _, b := range managedBlocks {
		start, end, ok := fsutil.FindBlock(cur, b.m)
		if !ok {
			continue
		}
		if touchesBlock(cur, start, end, e) {
			return fmt.Sprintf("strata: %s touches the managed block %s — edit outside the markers; regenerate with %#q", rel, b.m.BeginPrefix+"…", b.cmd)
		}
	}
	return ""
}

func stripComment(s string) string {
	s = strings.TrimPrefix(strings.TrimSpace(s), "<!--")
	return strings.TrimSuffix(strings.TrimSpace(s), "-->")
}

// touchesBlock reports whether an edit changes bytes inside [start,end).
func touchesBlock(cur []byte, start, end int, e EditInput) bool {
	if e.Content != "" || (e.OldString == "" && len(e.Edits) == 0) {
		// Write replaces the file: allowed only if the block survives verbatim.
		return e.Content != "" && !strings.Contains(e.Content, string(cur[start:end]))
	}
	olds := []string{e.OldString}
	for _, x := range e.Edits {
		olds = append(olds, x.OldString)
	}
	for _, o := range olds {
		if o == "" {
			continue
		}
		for i := 0; ; {
			j := bytes.Index(cur[i:], []byte(o))
			if j < 0 {
				break
			}
			s, t := i+j, i+j+len(o)
			if s < end && t > start {
				return true
			}
			i = s + 1
		}
	}
	return false
}

// advisory renders ≤ 3 lines of documents that apply to rel.
func (h *handler) advisory(rel string) (string, error) {
	ix, _, err := index.Open(h.ctx, h.inst, index.Options{})
	if err != nil {
		return "", err
	}
	defer func() { _ = ix.Close() }()
	hits, err := search.New(ix).Context(h.ctx, []string{rel}, 3)
	if err != nil || len(hits) == 0 {
		return "", err
	}
	verb := "apply"
	if len(hits) == 1 {
		verb = "applies"
	}
	lines := []string{fmt.Sprintf("ℹ strata: %s %s to this file:", render.Plural(len(hits), "document"), verb)}
	for _, x := range hits {
		lines = append(lines, render.Truncate("  "+x.ID+" — "+cmpOr(x.Summary, x.Title), 140))
	}
	return strings.Join(lines, "\n"), nil
}

func cmpOr(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

// postEdit runs edit-stage gates (and knowledge lint) on the touched file.
func (h *handler) postEdit() (outcome, error) {
	rel, ok := h.rel(h.in.EditPath())
	if !ok {
		return outcome{label: "outside"}, nil
	}
	var reports []string
	if h.isKnowledge(rel) && strings.HasSuffix(rel, ".md") {
		r, err := lint.Run(h.inst, lint.Options{Paths: []string{rel}})
		if err != nil {
			return outcome{}, err
		}
		if blocking := errorsOnly(r); len(blocking) > 0 {
			var b strings.Builder
			fmt.Fprintf(&b, "strata lint ✗ %s (%s)\n", render.Plural(len(blocking), "blocking finding"), rel)
			_ = render.Findings(&b, blocking)
			reports = append(reports, b.String())
		}
	}
	var gr GateResult
	if h.env.Gates != nil {
		var err error
		if gr, err = h.env.Gates(h.ctx, h.inst, "edit", []string{rel}); err != nil {
			return outcome{}, err
		}
		if gr.Blocking > 0 {
			reports = append(reports, gr.Report)
		}
	}
	err := update(h.inst.Root, h.in.SessionID, func(s *State) {
		h.noteEdit(s, rel)
		if len(reports) > 0 {
			s.GateFailures++
		}
	})
	if err != nil {
		return outcome{}, err
	}
	if len(reports) == 0 {
		return outcome{label: "clean"}, nil
	}
	msg := strings.Join(reports, "\n")
	if !strings.Contains(msg, "Fix these") {
		msg += "Fix these, then continue.\n"
	}
	return outcome{stderr: msg, code: 2, label: "blocked"}, nil
}

func errorsOnly(r *lint.Report) []finding.Finding {
	var out []finding.Finding
	for _, f := range r.Findings {
		if f.Severity == finding.Error {
			out = append(out, f)
		}
	}
	return out
}

// isKnowledge reports whether rel is under the knowledge tree.
func (h *handler) isKnowledge(rel string) bool {
	return strings.HasPrefix(rel, h.inst.Config.Paths.Knowledge+"/")
}

// noteEdit classifies an edit for the stop nudge: knowledge and project
// log/handoff edits count as capture; anything else is a code change.
func (h *handler) noteEdit(s *State, rel string) {
	layout := corpus.LayoutOf(h.inst.Config.Paths)
	switch {
	case h.isKnowledge(rel):
		s.Captured = true
	case strings.HasPrefix(rel, layout.Projects+"/"):
		if b := path.Base(rel); b == "log.md" || b == "handoff.md" {
			s.Captured = true
		}
	case strings.HasPrefix(rel, ".strata/") || strings.HasPrefix(rel, ".claude/"):
	default:
		s.CodeChanged = true
	}
}
