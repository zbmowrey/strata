func TestPreEditGuards(t *testing.T) {
	t.Parallel()
	root := fixture(t)
	testutil.WriteFile(t, root, "gen.md", "<!-- GENERATED by strata — edit scripts/**/script.yaml instead -->\nbody\n")
	testutil.WriteFile(t, root, "CLAUDE.md", "# Repo\n\nmine\n\n<!-- strata:begin v1 -->\nprotocol\n<!-- strata:end -->\n\ntail\n")
	cases := []struct {
		name, file, input string
		code              int
		want              string
	}{
		{"generated", "gen.md", `{"file_path":"FILE","old_string":"body","new_string":"x"}`, 2, "is generated — GENERATED by strata — edit scripts/**/script.yaml instead"},
		{"block edit", "CLAUDE.md", `{"file_path":"FILE","old_string":"protocol","new_string":"x"}`, 2, "managed block"},
		{"edit outside block", "CLAUDE.md", `{"file_path":"FILE","old_string":"mine","new_string":"x"}`, 0, ""},
		{"multiedit into block", "CLAUDE.md", `{"file_path":"FILE","edits":[{"old_string":"tail"},{"old_string":"strata:end"}]}`, 2, "managed block"},
		{"write keeps block", "CLAUDE.md", `{"file_path":"FILE","content":"new\n<!-- strata:begin v1 -->\nprotocol\n<!-- strata:end -->\n"}`, 0, ""},
		{"write drops block", "CLAUDE.md", `{"file_path":"FILE","content":"new\n"}`, 2, "managed block"},
		{"new file", "brand-new.go", `{"file_path":"FILE","content":"package x\n"}`, 0, ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			in := strings.ReplaceAll(c.input, "FILE", filepath.Join(root, c.file))
			stdin := `{"session_id":"s-` + c.name + `","cwd":"` + root + `","hook_event_name":"PreToolUse","tool_name":"Edit","tool_input":` + in + `}`
			r := run(t, "pre-edit", stdin, Env{})
			if r.code != c.code || !strings.Contains(r.err, c.want) {
				t.Fatalf("code %d stderr %q", r.code, r.err)
			}
		})
	}
}

