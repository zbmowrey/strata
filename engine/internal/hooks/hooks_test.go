var fixedNow = func() time.Time { return time.Date(2026, 11, 7, 12, 0, 0, 0, time.UTC) }

// payload loads a recorded hook payload, re-rooted at root.
func payload(t *testing.T, name, root string, edits ...string) string {
	t.Helper()
	raw, err := os.ReadFile(testutil.Fixture(filepath.Join("hooks", name+".json")))
	if err != nil {
		t.Fatal(err)
	}
	s := strings.ReplaceAll(string(raw), "/work/repo", filepath.ToSlash(root))
	for i := 0; i+1 < len(edits); i += 2 {
		s = strings.ReplaceAll(s, edits[i], edits[i+1])
	}
	return s
}

type result struct {
	out, err string
	code     int
}

func run(t *testing.T, event, stdin string, env Env) result {
	t.Helper()
	var out, errb bytes.Buffer
	env.Out, env.Err = &out, &errb
	if env.Now == nil {
		env.Now = fixedNow
	}
	code := Run(context.Background(), event, strings.NewReader(stdin), env)
	return result{out.String(), errb.String(), code}
}

func fixture(t *testing.T) string {
	t.Helper()
	return testutil.CopyFixture(t, "instance-basic")
}

func TestSessionStart(t *testing.T) {
	t.Parallel()
	root := fixture(t)
	called := false
	r := run(t, "session-start", payload(t, "session-start", root), Env{GardenAuto: func(context.Context, *config.Instance, []string) (string, error) {
		called = true
		return "garden --auto: 1 hub regenerated", nil
	}})
	if r.code != 0 || r.err != "" {
		t.Fatalf("code %d stderr %q", r.code, r.err)
	}
	lines := strings.Split(strings.TrimSpace(r.out), "\n")
	if len(lines) > 25 || !strings.HasPrefix(lines[0], "strata ▸ 40 shards · 5 scripts · 2 playbooks") {
		t.Fatalf("banner:\n%s", r.out)
	}
	for _, want := range []string{"garden --auto: 1 hub regenerated", "ci-flake — Next:", "Inbox 2", "Open questions 1"} {
		if !strings.Contains(r.out, want) {
			t.Errorf("banner missing %q:\n%s", want, r.out)
		}
	}
	if !called {
		t.Error("GardenAuto not called")
	}
	tel, _ := filepath.Glob(filepath.Join(root, ".strata", "telemetry", "*.jsonl"))
	if len(tel) == 0 {
		t.Fatal("no hook telemetry written")
	}
	if raw, _ := os.ReadFile(tel[0]); !strings.Contains(string(raw), `"hook":"session-start"`) {
		t.Errorf("hook event name not recorded: %s", raw)
	}
}

