func TestNormalizeCommand(t *testing.T) {
	t.Parallel()
	cases := map[string]string{
		`go test ./internal/... -run TestX -count=1`: "go test P -run TestX -count=N",
		`grep -n "secret value" /etc/hosts`:          "grep -n S P",
		`curl -s 'http://x/y'   |   jq .`:            "curl -s S | jq .",
		`sleep 30`:                                   "sleep N",
	}
	for in, want := range cases {
		if got := NormalizeCommand(in); got != want {
			t.Errorf("NormalizeCommand(%q) = %q, want %q", in, got, want)
		}
	}
	if CommandHash("sleep 1") != CommandHash("sleep  2") || CommandHash("sleep 1") == CommandHash("ls") {
		t.Error("hash should ignore numbers and whitespace only")
	}
	for in, want := range map[string]string{"FOO=1 BAR=x /usr/bin/env go": "env", "": "", "(cd x)": "cd"} {
		if got := FirstToken(in); got != want {
			t.Errorf("FirstToken(%q) = %q, want %q", in, got, want)
		}
	}
}

