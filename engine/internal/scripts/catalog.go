package scripts

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/zbmowrey/strata/engine/internal/config"
	"github.com/zbmowrey/strata/engine/internal/fsutil"
)

// CatalogHeader marks generated catalogs (D-019).
const CatalogHeader = "<!-- GENERATED by strata — edit scripts/**/script.yaml instead -->"

// CatalogFile is the catalog file name (root and per-domain).
const CatalogFile = "CATALOG.md"

// Catalog renders the catalog files: path (relative to the instance root)
// → content. With more than split scripts the root lists domains and each
// domain gets its own table (docs/spec/04-scriptorium.md §8).
func Catalog(scripts []Script, scriptsRoot string, split int) map[string][]byte {
	out := map[string][]byte{}
	root := scriptsRoot + "/" + CatalogFile
	if len(scripts) <= split {
		var b bytes.Buffer
		b.WriteString(CatalogHeader + "\n# Script catalog\n\n")
		fmt.Fprintf(&b, "%d scripts. Run with `strata run <id> -- <args>`; find with `strata search '<need> kind:script'`.\n\n", len(scripts))
		table(&b, scripts)
		out[root] = b.Bytes()
		return out
	}
	byDomain := map[string][]Script{}
	for _, s := range scripts {
		d := s.Domain
		if d == "" {
			d = "_root"
		}
		byDomain[d] = append(byDomain[d], s)
	}
	domains := make([]string, 0, len(byDomain))
	for d := range byDomain {
		domains = append(domains, d)
	}
	slices.Sort(domains)
	var b bytes.Buffer
	b.WriteString(CatalogHeader + "\n# Script catalog\n\n")
	fmt.Fprintf(&b, "%d scripts in %d domains. Run with `strata run <id> -- <args>`.\n\n| domain | scripts |\n|---|---|\n", len(scripts), len(domains))
	for _, d := range domains {
		fmt.Fprintf(&b, "| [%s](%s/%s) | %d |\n", d, d, CatalogFile, len(byDomain[d]))
		var db bytes.Buffer
		db.WriteString(CatalogHeader + "\n# Scripts: " + d + "\n\n")
		table(&db, byDomain[d])
		out[scriptsRoot+"/"+d+"/"+CatalogFile] = db.Bytes()
	}
	out[root] = b.Bytes()
	return out
}

func table(b *bytes.Buffer, scripts []Script) {
	b.WriteString("| id | summary | side effect | runtime | usage |\n|---|---|---|---|---|\n")
	for _, s := range scripts {
		summary := s.Summary
		if s.Status == "deprecated" {
			summary = "(deprecated" + replacement(s) + ") " + summary
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n", cell(s.ID), cell(summary), cell(s.SideEffect), cell(s.Runtime), code(s.Usage))
	}
}

func replacement(s Script) string {
	if s.ReplacedBy == "" {
		return ""
	}
	return " → " + s.ReplacedBy
}

func cell(s string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(s), " "), "|", `\|`)
}

func code(s string) string {
	if s = cell(s); s == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(s, "`", "'") + "`"
}

// WriteCatalog regenerates the catalog files, removing stale generated
// per-domain catalogs. It returns the paths written or removed.
func WriteCatalog(inst *config.Instance) ([]string, error) {
	all, err := Load(inst)
	if err != nil {
		return nil, err
	}
	sr := filepath.ToSlash(inst.Config.Paths.Scripts)
	files := Catalog(all, sr, inst.Config.Scripts.CatalogSplitAt)
	var changed []string
	keys := make([]string, 0, len(files))
	for k := range files {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	for _, rel := range keys {
		p := filepath.Join(inst.Root, filepath.FromSlash(rel))
		if old, err := os.ReadFile(p); err == nil && bytes.Equal(old, files[rel]) { //nolint:gosec // G304: generated catalog path
			continue
		}
		if err := fsutil.WriteAtomic(p, files[rel], 0o644); err != nil {
			return changed, err
		}
		changed = append(changed, rel)
	}
	stale, err := staleCatalogs(inst, sr, files)
	if err != nil {
		return changed, err
	}
	for _, rel := range stale {
		if err := os.Remove(filepath.Join(inst.Root, filepath.FromSlash(rel))); err != nil {
			return changed, fmt.Errorf("remove stale catalog: %w", err)
		}
		changed = append(changed, rel)
	}
	return changed, nil
}

// staleCatalogs finds generated per-domain catalogs no longer produced.
func staleCatalogs(inst *config.Instance, sr string, keep map[string][]byte) ([]string, error) {
	entries, err := os.ReadDir(filepath.Join(inst.Root, filepath.FromSlash(sr)))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("scan catalogs: %w", err)
	}
	var out []string
	for _, e := range entries {
		rel := sr + "/" + e.Name() + "/" + CatalogFile
		if !e.IsDir() || keep[rel] != nil {
			continue
		}
		b, err := os.ReadFile(filepath.Join(inst.Root, filepath.FromSlash(rel))) //nolint:gosec // G304: catalog path inside the instance
		if err == nil && bytes.HasPrefix(b, []byte(CatalogHeader)) {
			out = append(out, rel)
		}
	}
	return out, nil
}
