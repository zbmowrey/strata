// HubMarkers delimit the generated part of a hub; text above is preserved.
var HubMarkers = fsutil.Markers{
	Begin:       "<!-- strata:hub:begin — GENERATED, do not edit below -->",
	End:         "<!-- strata:hub:end -->",
	BeginPrefix: "<!-- strata:hub:begin",
}

// GeneratedHeader marks fully generated markdown files (D-019).
const GeneratedHeader = "<!-- GENERATED by strata — edit %s instead -->"

type hubShard struct {
	id, topic, summary, updated string
}

// Hubs regenerates knowledge/_hubs/hub-<domain>.md for every domain and the
// root index.md (filename stem == id, so links resolve in Obsidian too). It returns the paths it wrote (unchanged files are skipped).
func (s *Store) Hubs(ctx context.Context) ([]string, error) {
	l, err := s.lock()
	if err != nil {
		return nil, err
	}
	defer func() { _ = l.Unlock() }()
	domains, err := s.collectShards(ctx)
	if err != nil {
		return nil, err
	}
	hubDir := path.Join(s.layout.Knowledge, "_hubs")
	existing, err := s.existingHubs(hubDir)
	if err != nil {
		return nil, err
	}
	for d := range existing {
		if _, ok := domains[d]; !ok {
			domains[d] = nil // keep hand-written hubs; their block becomes empty
		}
	}
	names := make([]string, 0, len(domains))
	for d := range domains {
		names = append(names, d)
	}
	slices.Sort(names)
	var written []string
	summaries := map[string]string{}
	for _, d := range names {
		rel := path.Join(hubDir, "hub-"+d+".md")
		changed, summary, err := s.writeHub(rel, d, domains[d])
		if err != nil {
			return written, err
		}
		summaries[d] = summary
		if changed {
			written = append(written, rel)
		}
	}
	changed, err := s.writeIndex(path.Join(hubDir, "index.md"), names, domains, summaries)
	if err != nil {
		return written, err
	}
	if changed {
		written = append(written, path.Join(hubDir, "index.md"))
	}
	return written, nil
}

// collectShards groups active public shards by domain. It reads the index
// (refreshing it first), not the files: hubs are regenerated on every
// garden run, including the incremental SessionStart pass.
func (s *Store) collectShards(ctx context.Context) (map[string][]hubShard, error) {
	ix, _, err := index.Open(ctx, s.inst, index.Options{})
	if err != nil {
		return nil, err
	}
	defer func() { _ = ix.Close() }()
	k := s.layout.Knowledge + "/"
	rows, err := ix.DB().QueryContext(ctx, `SELECT src, topic, summary, updated FROM docs
		WHERE kind = 'shard' AND private = 0 AND status NOT IN ('superseded', 'archived')
		AND substr(src, 1, ?) = ? AND substr(src, ?, 1) != '_' ORDER BY src`, len(k), k, len(k)+1)
	if err != nil {
		return nil, fmt.Errorf("hubs: %w", err)
	}
	defer func() { _ = rows.Close() }()
	out := map[string][]hubShard{}
	for rows.Next() {
		var src, topic, summary, updated string
		if err := rows.Scan(&src, &topic, &summary, &updated); err != nil {
			return nil, fmt.Errorf("hubs: %w", err)
		}
		parts := strings.Split(strings.TrimPrefix(src, k), "/")
		if len(parts) < 3 {
			continue
		}
		out[parts[0]] = append(out[parts[0]], hubShard{
			id: strings.TrimSuffix(parts[len(parts)-1], ".md"), topic: parts[1], summary: summary, updated: updated,
		})
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("hubs: %w", err)
	}
	return out, nil
}

func (s *Store) existingHubs(dir string) (map[string]bool, error) {
	entries, err := os.ReadDir(s.abs(dir))
	if os.IsNotExist(err) {
		return map[string]bool{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("hubs: %w", err)
	}
	out := map[string]bool{}
	for _, e := range entries {
		if n := e.Name(); strings.HasPrefix(n, "hub-") && strings.HasSuffix(n, ".md") {
			out[strings.TrimSuffix(strings.TrimPrefix(n, "hub-"), ".md")] = true
		}
	}
	return out, nil
}

// HubBlock renders the generated section of a domain hub: topics by shard
// count desc (then name), shards by updated desc (then id).
func HubBlock(shards []hubShard) string {
	byTopic := map[string][]hubShard{}
	for _, sh := range shards {
		byTopic[sh.topic] = append(byTopic[sh.topic], sh)
	}
	topics := make([]string, 0, len(byTopic))
	for t := range byTopic {
		topics = append(topics, t)
	}
	slices.SortFunc(topics, func(a, b string) int { return cmp.Or(cmp.Compare(len(byTopic[b]), len(byTopic[a])), cmp.Compare(a, b)) })
	var b strings.Builder
	for i, t := range topics {
		if i > 0 {
			b.WriteString("\n")
		}
		list := byTopic[t]
		slices.SortFunc(list, func(x, y hubShard) int { return cmp.Or(cmp.Compare(y.updated, x.updated), cmp.Compare(x.id, y.id)) })
		fmt.Fprintf(&b, "## %s  (%d)\n", t, len(list))
		for _, sh := range list {
			fmt.Fprintf(&b, "- [[%s]] — %s\n", sh.id, truncateRunes(sh.summary, 100))
		}
	}
	if len(topics) == 0 {
		b.WriteString("_No active shards in this domain._\n")
	}
	return b.String()
}

func truncateRunes(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	// Cut at a word boundary so hub lines never end in a word fragment
	// (spell checkers flag cut-off words).
	cut := string(r[:n-1])
	if i := strings.LastIndexByte(cut, ' '); i > len(cut)/2 {
		cut = cut[:i]
	}
	return strings.TrimRight(cut, " ,;:—-") + "…"
}

// writeHub regenerates one hub, preserving frontmatter and intro.
func (s *Store) writeHub(rel, domain string, shards []hubShard) (bool, string, error) {
	raw, err := os.ReadFile(s.abs(rel)) //nolint:gosec // G304: hub path inside the instance
	if os.IsNotExist(err) {
		raw = []byte("---\nid: hub-" + domain + "\ntitle: " + Value(titleCase(domain)) +
			"\nsummary: " + Value("Map of everything known about "+domain+" in this repository.") + "\ntype: index\n---\n")
	} else if err != nil {
		return false, "", fmt.Errorf("hub %s: %w", rel, err)
	}
	out, _ := fsutil.ReplaceBlock(raw, HubMarkers, HubBlock(shards))
	m, _ := metaOf(out)
	summary := ""
	if m != nil {
		summary = m.String("summary")
	}
	if bytes.Equal(out, raw) {
		return false, summary, nil
	}
	return true, summary, s.writeFile(rel, out)
}

func (s *Store) writeIndex(rel string, names []string, domains map[string][]hubShard, summaries map[string]string) (bool, error) {
	var b strings.Builder
	b.WriteString("---\nid: index\ntitle: Knowledge map\nsummary: Every knowledge domain in this repository with shard counts.\ntype: index\n---\n")
	fmt.Fprintf(&b, GeneratedHeader+"\n\n", "knowledge/<domain>/** (then run `strata hubs`)")
	for _, d := range names {
		fmt.Fprintf(&b, "- [[hub-%s]] — %d shards — %s\n", d, len(domains[d]), summaries[d])
	}
	out := []byte(b.String())
	if old, err := os.ReadFile(s.abs(rel)); err == nil && bytes.Equal(old, out) { //nolint:gosec // G304: hub path inside the instance
		return false, nil
	}
	return true, s.writeFile(rel, out)
}

func titleCase(s string) string {
	words := strings.FieldsFunc(s, func(r rune) bool { return r == '-' || r == '_' })
	for i, w := range words {
		r := []rune(w)
		r[0] = unicode.ToUpper(r[0])
		words[i] = string(r)
	}
	return strings.Join(words, " ")
}
