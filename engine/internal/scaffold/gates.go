//go:embed templates/gates/*.toml
var gateTemplates embed.FS

// Profiles lists the gate profiles in render order (docs/spec/06-gates.md §4).
var Profiles = []string{"go", "python", "ts", "rust", "shell", "docs", "security"}

// always-on profiles: every instance gets knowledge lint, spelling and
// secret/suppression checks.
var alwaysProfiles = []string{"docs", "security"}

// detectors map a profile to marker files found at the root or one level down.
var detectors = map[string][]string{
	"go":     {"go.mod"},
	"python": {"pyproject.toml", "requirements.txt", "setup.py", "uv.lock"},
	"ts":     {"tsconfig.json"},
	"rust":   {"Cargo.toml"},
}

// skipDetect are directories never searched for language markers.
var skipDetect = map[string]bool{".git": true, "node_modules": true, ".venv": true, "vendor": true, "target": true, "testdata": true}

// DetectProfiles returns the gate profiles for the languages present in
// root (markers at the root or in a first- or second-level directory, *.sh
// files anywhere shallow), plus the always-on docs and security profiles.
func DetectProfiles(root string) []string {
	found := map[string]bool{}
	for _, p := range alwaysProfiles {
		found[p] = true
	}
	_ = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil //nolint:nilerr // unreadable entries are simply not markers
		}
		if d.IsDir() {
			return descend(root, p, d)
		}
		for _, prof := range markerProfiles(d.Name()) {
			found[prof] = true
		}
		return nil
	})
	var out []string
	for _, p := range Profiles {
		if found[p] {
			out = append(out, p)
		}
	}
	return out
}

// descend decides whether DetectProfiles walks into directory p.
func descend(root, p string, d fs.DirEntry) error {
	if p == root {
		return nil
	}
	rel, _ := filepath.Rel(root, p)
	if skipDetect[d.Name()] || strings.HasPrefix(d.Name(), ".") || strings.Count(filepath.ToSlash(rel), "/") >= 2 {
		return filepath.SkipDir
	}
	return nil
}

// markerProfiles returns the profiles a file name indicates.
func markerProfiles(name string) []string {
	var out []string
	for prof, markers := range detectors {
		if slices.Contains(markers, name) {
			out = append(out, prof)
		}
	}
	if strings.HasSuffix(name, ".sh") || strings.HasSuffix(name, ".bash") {
		out = append(out, "shell")
	}
	return out
}

// ErrUnknownProfile is returned for profile names outside Profiles.
var ErrUnknownProfile = errors.New("unknown gate profile")

// RenderGates concatenates the gate templates of the given profiles into a
// .strata/gates.toml document.
func RenderGates(profiles []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("# Strata gates (docs/spec/06-gates.md). Generated by `strata init` for profiles: " +
		strings.Join(profiles, ", ") + ".\n# This file is yours: edit gates freely; disabling one requires `reason = \"…\"`.\n\n")
	for _, p := range profiles {
		if !slices.Contains(Profiles, p) {
			return nil, fmt.Errorf("%w %q (known: %s)", ErrUnknownProfile, p, strings.Join(Profiles, ", "))
		}
		raw, err := gateTemplates.ReadFile("templates/gates/" + p + ".toml")
		if err != nil {
			return nil, fmt.Errorf("gate template %s: %w", p, err)
		}
		b.Write(raw)
		b.WriteString("\n")
	}
	return b.Bytes(), nil
}

// ToolPin is one pinned tool in .strata/tools.toml.
type ToolPin struct {
	Profile string   `toml:"profile"`
	Version string   `toml:"version"`
	Install string   `toml:"install"`
	Check   []string `toml:"check"`
}

// ToolPins returns the pins for the given profiles, keyed by tool name.
func ToolPins(profiles []string) (map[string]ToolPin, error) {
	raw, err := gateTemplates.ReadFile("templates/gates/tools.toml")
	if err != nil {
		return nil, fmt.Errorf("tool pins: %w", err)
	}
	var all struct {
		Tools map[string]ToolPin `toml:"tools"`
	}
	if err := toml.Unmarshal(raw, &all); err != nil {
		return nil, fmt.Errorf("tool pins: %w", err)
	}
	out := map[string]ToolPin{}
	for name, pin := range all.Tools {
		if slices.Contains(profiles, pin.Profile) {
			out[name] = pin
		}
	}
	return out, nil
}

// RenderTools renders .strata/tools.toml for the given profiles
// (deterministic: tools sorted by name).
func RenderTools(profiles []string) ([]byte, error) {
	pins, err := ToolPins(profiles)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(pins))
	for n := range pins {
		names = append(names, n)
	}
	slices.Sort(names)
	var b bytes.Buffer
	b.WriteString("# Pinned tool versions checked by `strata doctor` (docs/spec/06-gates.md §4).\n")
	for _, n := range names {
		p := pins[n]
		fmt.Fprintf(&b, "\n[tools.%s]\nprofile = %q\nversion = %q\ncheck = [%s]\ninstall = %q\n", n, p.Profile, p.Version, quoteList(p.Check), p.Install)
	}
	return b.Bytes(), nil
}

func quoteList(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = fmt.Sprintf("%q", x)
	}
	return strings.Join(q, ", ")
}

